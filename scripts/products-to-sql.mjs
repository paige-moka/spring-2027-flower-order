// Writes supabase/migrations/0002_seed_products.sql from data/products.json.
// Usage: npm run products:sql
import fs from 'node:fs';

const data = JSON.parse(fs.readFileSync('data/products.json', 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = data.items.map(
  (it) => `  (${it.item_no}, ${q(it.family)}, ${q(it.name)}, ${q(it.size)}, ${Math.round(it.price * 100)}, ${it.page})`,
);
const sql = `-- Product list taken from the catalogue PDF (${data.source_pdf}, ${data.pages} pages)
-- PDF SHA-256: ${data.source_sha256}
-- ${data.items.length} item numbers. Generated by scripts/products-to-sql.mjs. Safe to run again.

insert into public.products (item_no, family, name, size, price_cents, catalogue_page) values
${rows.join(',\n')}
on conflict (item_no) do update set
  family = excluded.family, name = excluded.name, size = excluded.size,
  price_cents = excluded.price_cents, catalogue_page = excluded.catalogue_page, active = true;

-- Any item no longer in the catalogue is switched off (kept for old orders, never deleted).
update public.products set active = false
where item_no not in (${data.items.map((i) => i.item_no).join(', ')});
`;
fs.writeFileSync('supabase/migrations/0002_seed_products.sql', sql);
console.log(`Wrote ${data.items.length} products to supabase/migrations/0002_seed_products.sql`);
